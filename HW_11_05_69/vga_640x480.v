`timescale 1ns / 1ps


// ============================================================================
// เครื่องกำเนิดสัญญาณ VGA ความละเอียด 640x480 ที่อัตรารีเฟรช 60 Hz
// ทำหน้าที่สร้างพิกัดพิกเซล (X,Y) และสัญญาณควบคุมจังหวะหน้าจอ (Hsync, Vsync)
// ============================================================================
module vga_640x480 (
    // สัญญาณนาฬิกาหลัก ต้องเป็น 25 MHz เท่านั้นสำหรับความละเอียด 640x480 @ 60Hz
    input  wire       clk25,
   
    // พิกัดหัวอ่านปัจจุบันบนหน้าจอ
    output reg [9:0]  sx = 0, // แกน X (แนวนอน) นับตั้งแต่ 0 - 799
    output reg [9:0]  sy = 0, // แกน Y (แนวตั้ง) นับตั้งแต่ 0 - 524
   
    // สัญญาณควบคุมจอภาพ (มาตรฐาน VGA ใช้ Active-Low คือเป็น 0 เมื่อสั่งการ)
    output wire       hsync,  // สั่งให้หัวอ่านปัดกลับไปเริ่มบรรทัดใหม่ทางซ้าย
    output wire       vsync,  // สั่งให้หัวอ่านปัดกลับไปเริ่มเฟรมใหม่ที่มุมซ้ายบน
   
    // สัญญาณรับรองพื้นที่แสดงผล
    output wire       active_video, // เป็น 1 เมื่อหัวอ่านอยู่ในพื้นที่ที่อนุญาตให้ส่งสีออกไปได้
    output wire       frame_start   // ส่งสัญญาณ Pulse สั้นๆ 1 จังหวะ เมื่อเริ่มวาดเฟรมใหม่
);


    // ============================================================================
    // สเปคมาตรฐานเวลาของ VGA 640x480 @ 60 Hz (ใช้ Clock 25 MHz)
    // ----------------------------------------------------------------------------
    // แกนนอน (Horizontal): วาดภาพจริง 640, เว้นหน้า(FP) 16, สั่งซิงค์ 96, เว้นหลัง(BP) 48
    // รวม 1 บรรทัดต้องนับให้ครบ = 800 จังหวะ (Clock)
    //
    // แกนตั้ง (Vertical): วาดภาพจริง 480, เว้นหน้า(FP) 10, สั่งซิงค์ 2, เว้นหลัง(BP) 33
    // รวม 1 หน้าจอต้องกวาดให้ครบ = 525 บรรทัด
    // ============================================================================


    // ============================================================================
    // ส่วนที่ 1: วงจรนับตำแหน่งพิกัด (Coordinate Counters)
    // ============================================================================
    // ทำงานทุกๆ ขอบขาขึ้นของ Clock 25 MHz (1 Clock = ขยับหัวอ่านไปทางขวา 1 พิกเซล)
    always @(posedge clk25) begin
       
        // ถ้าหัวอ่านวิ่งไปจนสุดขอบแนวนอนของเส้นทาง (พิกเซลที่ 799)
        if (sx == 799) begin
            sx <= 0; // ดึงหัวอ่านกลับมาที่พิกัด 0 ทางซ้ายสุด
           
            // เมื่อจบบรรทัด ให้เช็คว่ากวาดครบทุกบรรทัดในแนวตั้งหรือยัง (บรรทัดที่ 524)
            if (sy == 524)
                sy <= 0; // ถ้าครบแล้ว ให้ดึงหัวอ่านกลับไปบรรทัดบนสุด (เริ่มเฟรมใหม่)
            else          
                sy <= sy + 1; // ถ้ายังไม่ครบ ให้ปัดลงมาวาดบรรทัดถัดไป
               
        // ถ้ายังไม่สุดขอบแนวนอน
        end else begin
            sx <= sx + 1; // เลื่อนหัวอ่านไปทางขวาเรื่อยๆ ทีละ 1 พิกเซล
        end
    end
    // ============================================================================
    // ส่วนที่ 2: สร้างสัญญาณควบคุมจอ (Sync Generation)
    // ============================================================================
    // สัญญาณ HSYNC (แนวนอน): ทำงานเป็น Active-Low (ใส่ ~ เพื่อกลับบิต)
    // จอจะรับรู้คำสั่ง HSYNC ในช่วงพิกัด: วาดภาพ(640) + หน้า(16) = เริ่มที่พิกัด 656
    // ความกว้างของคำสั่งคือ 96 จังหวะ ดังนั้นจะสิ้นสุดที่: 656 + 96 = พิกัด 752
    assign hsync = ~((sx >= 656) && (sx < 752));


    // สัญญาณ VSYNC (แนวตั้ง): ทำงานเป็น Active-Low (ใส่ ~ เพื่อกลับบิต)
    // จอจะรับรู้คำสั่ง VSYNC ในช่วงบรรทัด: วาดภาพ(480) + หน้า(10) = เริ่มที่บรรทัด 490
    // ความกว้างของคำสั่งคือ 2 บรรทัด ดังนั้นจะสิ้นสุดที่: 490 + 2 = บรรทัด 492
    assign vsync = ~((sy >= 490) && (sy < 492));


    // ============================================================================
    // ส่วนที่ 3: ระบุพื้นที่วาดภาพ (Blanking Qualification)
    // ============================================================================
    // active_video จะเป็น 1 ก็ต่อเมื่อหัวอ่านอยู่ในพื้นที่ 640x480 เท่านั้น
    // หากเกินกว่านี้ (อยู่ในช่วง Porch หรือ Sync) จะเป็น 0
    // (ระบบข้างนอกต้องนำค่านี้ไปตัดให้สี RGB เป็นดำ (0) ในช่วงนี้ ไม่เช่นนั้นจอจะรวน)
    assign active_video = (sx < 640) && (sy < 480);


    // สร้างสัญญาณเตือนวงจรภายนอกว่า "กำลังเริ่มวาดภาพแผ่นใหม่แล้วนะ"
    assign frame_start  = (sx == 0) && (sy == 0);


endmodule

`timescale 1ns / 1ps

// ============================================================================
// โมดูลสร้างจังหวะหน้าจอ VGA (VGA Timing Generator)
// *หมายเหตุสำคัญ:* ชื่อโมดูลเดิมคือ vga_640x480 (เพื่อไม่ให้ Vivado พัง)
// แต่ไส้ในถูกอัปเกรดเป็นความละเอียดระดับ HD 1280x960 @ 60 Hz เรียบร้อยแล้ว!
// ต้องใช้ Clock ความถี่ 108 MHz ในการขับเคลื่อน
// ============================================================================
module vga_640x480 (
    input  wire       clk25,        // **คำเตือน: สัญญาณที่ป้อนเข้าพอร์ตนี้คือ 108 MHz (ไม่ใช่ 25 MHz แล้ว)**
    output reg [10:0] sx = 0,       // ตัวนับพิกัดแกน X (แนวนอน) วิ่งตั้งแต่ 0 ถึง 1799
    output reg [9:0]  sy = 0,       // ตัวนับพิกัดแกน Y (แนวตั้ง) วิ่งตั้งแต่ 0 ถึง 999
    output wire       hsync,        // สัญญาณเคาะจังหวะแนวนอนส่งให้จอ
    output wire       vsync,        // สัญญาณเคาะจังหวะแนวตั้งส่งให้จอ
    output wire       active_video, // 1 = หัวอ่านกำลังอยู่บนพื้นที่แสดงผลภาพ (ไม่ใช่ขอบจอดำ)
    output wire       frame_start   // 1 = หัวอ่านกลับไปมุมซ้ายบนสุด (เตรียมวาดเฟรมใหม่)
);

    // ========================================================================
    // มาตรฐาน VESA Timing สำหรับ 1280x960 @ 60 Hz (ใช้ 108 MHz Pixel Clock)
    // ========================================================================
    // แนวนอน (Horizontal): รวมทั้งหมด = 1800 พิกเซล (0 ถึง 1799)
    //   - พื้นที่แสดงภาพ (Visible): 1280 พิกเซล (sx: 0 ถึง 1279)
    //   - ขอบจอดำด้านขวา (Front Porch): 96 พิกเซล
    //   - จังหวะซิงค์ (Sync Pulse): 112 พิกเซล  <-- จุดนี้แหละที่สร้าง HSYNC
    //   - ขอบจอดำด้านซ้าย (Back Porch): 312 พิกเซล
    //
    // แนวตั้ง (Vertical): รวมทั้งหมด = 1000 บรรทัด (0 ถึง 999)
    //   - พื้นที่แสดงภาพ (Visible): 960 บรรทัด (sy: 0 ถึง 959)
    //   - ขอบจอดำด้านล่าง (Front Porch): 1 บรรทัด
    //   - จังหวะซิงค์ (Sync Pulse): 3 บรรทัด  <-- จุดนี้แหละที่สร้าง VSYNC
    //   - ขอบจอดำด้านบน (Back Porch): 36 บรรทัด

    // ========================================================================
    // ส่วนที่ 1: ตัวนับพิกัด (Pixel Counters)
    // ========================================================================
    always @(posedge clk25) begin
        // ถ้าวิ่งสุดขอบขวาแล้ว (1799) ให้ปัดกลับไปซ้ายสุด (0)
        if (sx == 1799) begin
            sx <= 0;
            // ถ้าวิ่งสุดขอบล่างแล้ว (999) ให้ปัดหัวเขียนกลับไปบนสุดเพื่อเริ่มเฟรมใหม่
            if (sy == 999) sy <= 0;
            else           sy <= sy + 1; // เลื่อนลงมา 1 บรรทัด
        end else begin
            sx <= sx + 1; // ขยับหัวเขียนไปทางขวาทีละ 1 พิกเซล
        end
    end

    // ========================================================================
    // ส่วนที่ 2: สร้างสัญญาณ Sync และ Active Video
    // ========================================================================
    // สัญญาณ HSYNC เป็น Positive Pulse (1) จะเริ่มทำงานในช่วงจังหวะ Sync แนวนอน
    // คำนวณจาก: Visible(1280) + FrontPorch(96) = เริ่มที่ 1376
    // จบที่: 1376 + SyncPulse(112) = จบที่ 1488 (ดังนั้นคือ 1376 ถึง 1487)
    assign hsync = (sx >= 1376) && (sx < 1488);

    // สัญญาณ VSYNC เป็น Positive Pulse (1) จะเริ่มทำงานในช่วงจังหวะ Sync แนวตั้ง
    // คำนวณจาก: Visible(960) + FrontPorch(1) = เริ่มที่ 961
    // จบที่: 961 + SyncPulse(3) = จบที่ 964 (ดังนั้นคือ 961 ถึง 963)
    assign vsync = (sy >= 961) && (sy < 964);

    // สัญญาณบอกว่า "ตอนนี้หยิบภาพมาโชว์ได้เลย" 
    // จะเป็น 1 แค่ตอนที่หัวเขียนอยู่ในพื้นที่ 1280x960 เท่านั้น
    assign active_video = (sx < 1280) && (sy < 960);

    // สัญญาณทริกเกอร์ 1 Clock Cycle ไว้บอกจังหวะเริ่มเฟรมใหม่
    assign frame_start  = (sx == 0) && (sy == 0);

endmodule
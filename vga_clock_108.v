`timescale 1ns / 1ps

// ============================================================================
// โมดูลแปลงความถี่นาฬิกา (Clock Generator) 
// จาก 100 MHz (ของบอร์ด Basys 3) -> เป็น 108 MHz (สำหรับจอ VGA 1280x960)
// ============================================================================
module vga_clock_108 (
    input  wire clk100, // นาฬิกาต้นทางจากคริสตัลบนบอร์ด (100 MHz)
    output wire clk108, // นาฬิกาปลายทางที่ปั่นเสร็จแล้ว (108 MHz)
    output wire locked  // สัญญาณบอกสถานะ (1 = ความถี่นิ่งและพร้อมใช้งานแล้ว)
);

// ============================================================================
// ส่วนที่ 1: โหมดจำลองการทำงาน (Simulation Bypass)
// ============================================================================
// ถ้าเรากำลังรันจำลองการทำงาน (Simulate) ด้วยโปรแกรม Icarus Verilog 
// โปรแกรมมันจะไม่รู้จักฮาร์ดแวร์ MMCM ของ Xilinx โค้ดส่วนนี้จึงสั่งให้เชื่อมสายตรงเลย
// (อนุโลมให้ใช้ 100 MHz แทน 108 MHz ไปก่อนตอนทำ Simulation เพื่อให้คอมไพล์ผ่าน)
`ifdef __ICARUS__
    assign clk108 = clk100;
    assign locked = 1'b1;
`else

// ============================================================================
// ส่วนที่ 2: โหมดใช้งานจริงบนบอร์ด (Hardware Synthesis)
// ============================================================================
    wire clkfb_unbuf;     // สาย Feedback ก่อนเข้า Buffer
    wire clkfb;           // สาย Feedback หลังเข้า Buffer (เอาไว้ให้วงจรเช็คว่าความถี่นิ่งหรือยัง)
    wire clk108_unbuf;    // สาย 108 MHz ดิบๆ ที่เพิ่งปั่นเสร็จ

    // เรียกใช้ IP ของ Xilinx (MMCME2_BASE) ซึ่งเป็นวงจรคูณ/หารความถี่ (PLL)
    // ------------------------------------------------------------------------
    // **สมการคณิตศาสตร์การปั่น Clock ของ Xilinx:**
    // F_out = F_in * (M / (D * O))
    // 
    // F_in (CLKIN1) = 100 MHz (คาบ 10.000 ns)
    // D (DIVCLK_DIVIDE) = หาร 5  -> ได้ความถี่ฐาน = 20 MHz
    // M (CLKFBOUT_MULT) = คูณ 54 -> ได้ความถี่แกนกลาง (VCO) = 1080 MHz
    // O (CLKOUT0_DIVIDE)= หาร 10 -> ได้ความถี่ส่งออก (F_out) = 108 MHz เป๊ะ!
    // ------------------------------------------------------------------------
    MMCME2_BASE #(
        .BANDWIDTH("OPTIMIZED"),
        .CLKFBOUT_MULT_F(54.000),   // ตัวคูณ (Multiplier = M)
        .CLKFBOUT_PHASE(0.000),
        .CLKIN1_PERIOD(10.000),     // คาบเวลาขาเข้า 10ns = 100 MHz
        .CLKOUT0_DIVIDE_F(10.000),  // ตัวหารขาออก (Output Divider = O)
        .CLKOUT0_DUTY_CYCLE(0.500), // อัตราส่วน High/Low แบบ 50:50
        .CLKOUT0_PHASE(0.000),
        .DIVCLK_DIVIDE(5),          // ตัวหารขาเข้า (Input Divider = D)
        .REF_JITTER1(0.010),        // ค่าเผื่อความแกว่งของสัญญาณ
        .STARTUP_WAIT("FALSE")
    ) mmcm_u (
        .CLKIN1(clk100),        // ป้อน 100 MHz เข้าไป
        .CLKFBIN(clkfb),        // รับสาย Feedback กลับเข้ามาเช็คความแม่นยำ
        .CLKFBOUT(clkfb_unbuf), // ปล่อยสาย Feedback ออกไป
        .CLKOUT0(clk108_unbuf), // ปล่อยผลลัพธ์ 108 MHz ออกมาทางช่อง 0
        .CLKOUT1(), .CLKOUT2(), .CLKOUT3(), .CLKOUT4(), .CLKOUT5(), .CLKOUT6(), // ช่องอื่นไม่ได้ใช้
        .LOCKED(locked),        // ขา Output บอกว่าตอนนี้ความถี่นิ่ง 108 MHz แล้วนะ
        .PWRDWN(1'b0),          // ไม่เปิดโหมดประหยัดพลังงาน
        .RST(1'b0)              // ไม่ต้องรีเซ็ต (ทำงานทันทีที่เปิดเครื่อง)
    );

    // ========================================================================
    // ส่วนที่ 3: จัดการสายสัญญาณนาฬิกา (Global Clock Buffers)
    // ========================================================================
    // สัญญาณนาฬิกาเป็นสัญญาณที่ซีเรียส ต้องเดินทางไปถึงทุกชิ้นส่วนพร้อมกัน 
    // เราจึงต้องเอาสัญญาณดิบไปผ่าน BUFG (Global Clock Buffer) 
    // เพื่อดันสัญญาณให้วิ่งเข้าไปใน "ท่อพิเศษสำหรับ Clock" ของชิป FPGA

    // จับ 108 MHz ดิบๆ ยัดเข้า BUFG
    BUFG clk108_bufg_u (
        .I(clk108_unbuf),
        .O(clk108) // กลายเป็น clk108 ที่แข็งแรงและพร้อมใช้งาน!
    );

    // จับสัญญาณ Feedback ยัดเข้า BUFG 
    // (เพื่อให้ MMCM คำนวณความหน่วงของวงจรได้อย่างแม่นยำ)
    BUFG clkfb_bufg_u (
        .I(clkfb_unbuf),
        .O(clkfb)
    );
`endif
endmodule